-- M00.05 transactional outbox. MySQL 8.4 / InnoDB; all technical timestamps are UTC DATETIME(3).
CREATE TABLE campus_outbox (
    event_id           VARCHAR(128) NOT NULL,
    event_type         VARCHAR(160) NOT NULL,
    event_version      INT NOT NULL,
    aggregate_id       VARCHAR(128) NOT NULL,
    aggregate_version  BIGINT NOT NULL,
    school_id          VARCHAR(128) NOT NULL,
    occurred_at        DATETIME(3) NOT NULL,
    trace_id           VARCHAR(128) NULL,
    payload_json       JSON NOT NULL,
    status             VARCHAR(16) NOT NULL,
    next_run_at        DATETIME(3) NOT NULL,
    attempt            INT NOT NULL DEFAULT 0,
    max_attempts       INT NOT NULL,
    lease_owner        VARCHAR(128) NULL,
    lease_until        DATETIME(3) NULL,
    lease_token        BIGINT NOT NULL DEFAULT 0,
    target_consumer    VARCHAR(128) NULL,
    last_consumer      VARCHAR(128) NULL,
    last_error_code    VARCHAR(64) NULL,
    last_error_reason  VARCHAR(500) NULL,
    row_version        BIGINT NOT NULL DEFAULT 1,
    replay_consumer    VARCHAR(128) NULL,
    replay_reason      VARCHAR(500) NULL,
    replayed_at        DATETIME(3) NULL,
    completed_at       DATETIME(3) NULL,
    create_time        DATETIME(3) NOT NULL,
    update_time        DATETIME(3) NOT NULL,
    PRIMARY KEY (event_id),
    KEY idx_campus_outbox_pending_claim (status, next_run_at, event_id),
    KEY idx_campus_outbox_expired_claim (status, lease_until, event_id),
    CONSTRAINT ck_campus_outbox_status CHECK (status IN ('PENDING','PROCESSING','SUCCEEDED','DEAD_LETTER')),
    CONSTRAINT ck_campus_outbox_attempt CHECK (attempt >= 0 AND max_attempts > 0),
    CONSTRAINT ck_campus_outbox_lease_token CHECK (lease_token >= 0),
    CONSTRAINT ck_campus_outbox_row_version CHECK (row_version > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE campus_event_consumption (
    consumer           VARCHAR(128) NOT NULL,
    event_id           VARCHAR(128) NOT NULL,
    status             VARCHAR(16) NOT NULL,
    last_error_code    VARCHAR(64) NULL,
    last_error_reason  VARCHAR(500) NULL,
    completed_at       DATETIME(3) NULL,
    create_time        DATETIME(3) NOT NULL,
    update_time        DATETIME(3) NOT NULL,
    PRIMARY KEY (consumer, event_id),
    KEY idx_campus_event_consumption_event (event_id, status),
    CONSTRAINT ck_campus_event_consumption_status CHECK (status IN ('PROCESSING','FAILED','SUCCEEDED')),
    CONSTRAINT fk_campus_event_consumption_event FOREIGN KEY (event_id) REFERENCES campus_outbox (event_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
